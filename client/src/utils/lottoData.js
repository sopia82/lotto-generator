export function getFallbackStats(count = 30) {
  const target = FALLBACK_DRAWS.slice(0, count);
  const latestDraw = target[0];

  const frequency = {};
  for (let n = 1; n <= 45; n++) {
    frequency[n] = 0;
  }

  target.forEach((draw) => {
    draw.numbers.forEach((num) => {
      if (frequency[num] !== undefined) {
        frequency[num]++;
      }
    });
  });

  const sorted = Object.entries(frequency)
    .map(([num, freq]) => ({ number: Number(num), count: freq }))
    .sort((a, b) => b.count - a.count);

  const hotNumbers = sorted.slice(0, 5).map((item) => item.number);
  const coldNumbers = sorted.slice(-5).map((item) => item.number);

  return {
    latestDraw,
    analyzedDrawsCount: target.length,
    startDrawNo: target[target.length - 1]?.drwNo,
    endDrawNo: latestDraw.drwNo,
    frequency,
    hotNumbers,
    coldNumbers,
    recentDraws: target.slice(0, 10)
  };
}
